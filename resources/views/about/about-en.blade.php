        USIM Framework is a software solution designed to support the development,
        management, and optimization of institutional information systems. It aims to
        offer a robust, scalable, and efficient platform for academic and administrative
        environments.
    </p>

    <p>
        This project is currently in version <strong>1.0.0</strong>, representing the
        initial release of the framework and establishing a solid foundation for future
        enhancements and extensions.
    </p>

    <p>
        USIM Framework was developed by the <strong>Instituto de Informática</strong>
        of the <strong>Facultad de Ciencias Exactas, Físicas y Naturales</strong> at
        the <strong>Universidad Nacional de San Juan</strong>.
    </p>
